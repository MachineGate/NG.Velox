namespace NG.Velox.Context.Interfaces
{
    using NG.Velox.Interpretation.Data;
    using NG.Velox.Parsing.Data;

    /// <summary>
    /// Defines the execution context interface for the primary lexical and semantic interpretation phase of the pipeline.
    /// </summary>
    /// <remarks>
    /// Exposes unified access to the parser's Abstract Syntax Tree alongside the property for publishing 
    /// hardware-ready execution state frames. The interpreter no longer inspects the raw source buffer — all 
    /// structural block boundaries arrive precomputed as <see cref="NG.Velox.Parsing.Data.NodeKind.NewLine"/> markers.
    /// </remarks>
    internal interface IInterpretationContext : IArenaContext
    {
        /// <summary>
        /// Gets the immutable Abstract Syntax Tree (AST) components generated by the parser.
        /// </summary>
        /// <value>
        /// The <see cref="ParsingResult"/> structure containing the syntax tokens and numbers extracted from the stream.
        /// </value>
        ParsingResult ParsingResult { get; }

        /// <summary>
        /// Sets the interpretation container where hardware-ready state frames are recorded.
        /// </summary>
        /// <value>
        /// The <see cref="InterpretationResult"/> structural container used to store generated execution frames.
        /// </value>
        InterpretationResult InterpretationResult { set; }
    }
}
